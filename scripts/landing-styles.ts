/**
 * Regenerates src/components/landing/styles.ts from the landing stylesheets.
 * Landing CSS uses an explicit `tenderLanding_` class namespace because the shared
 * Turbopack CSS rule does not emit CSS-module exports. Run: `bun scripts/landing-styles.ts`.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "landing");
const names = new Set<string>();
for (const file of readdirSync(dir).filter((name) => name.endsWith(".css")).sort()) {
  const css = readFileSync(join(dir, file), "utf8");
  for (const match of css.matchAll(/\.tenderLanding_([A-Za-z][A-Za-z0-9]*)/g)) names.add(match[1]);
}
const sorted = [...names].sort();
const body = sorted.map((name) => `  ${name}: "tenderLanding_${name}",`).join("\n");
writeFileSync(
  join(dir, "styles.ts"),
  `// Generated by scripts/landing-styles.ts from src/components/landing/*.css. Do not edit.\nexport const landingStyles = {\n${body}\n} as const;\n`,
);
console.log(`landing styles: ${sorted.length} classes`);
